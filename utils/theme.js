export const THEME_STORAGE_KEY = 'infodepo_theme';
export const DEFAULT_THEME = 'indigo';

export function readTheme() {
  try {
    const raw = localStorage.getItem(THEME_STORAGE_KEY);
    if (raw && THEMES[raw]) return raw;
  } catch {}
  return DEFAULT_THEME;
}

export function writeTheme(id) {
  try {
    localStorage.setItem(THEME_STORAGE_KEY, id);
  } catch {}
}

export function applyTheme(id) {
  const theme = THEMES[id] || THEMES[DEFAULT_THEME];
  const root = document.documentElement;
  for (const [shade, rgb] of Object.entries(theme.shades)) {
    root.style.setProperty(`--theme-${shade}`, rgb);
  }
  root.style.setProperty('--theme-button-text', theme.shades[theme.buttonTextShade]);
}

applyTheme(readTheme());
